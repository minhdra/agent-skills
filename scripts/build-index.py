#!/usr/bin/env python3
"""Check skills/ against groups.json and regenerate INDEX.md.

Usage: python3 -I scripts/build-index.py
Fails (exit 1) if a skill is in no group, in two groups, listed but missing,
or if its frontmatter name differs from its directory name.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"


def frontmatter(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}
    lines = m.group(1).split("\n")
    out, key, buf = {}, None, []
    for line in lines:
        km = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", line)
        if km and not line.startswith(" "):
            if key:
                out[key] = " ".join(buf).strip()
            key, buf = km.group(1), [km.group(2)]
        elif key:
            buf.append(line.strip())
    if key:
        out[key] = " ".join(buf).strip()
    for k, v in out.items():
        v = re.sub(r"^(>-|>|\|-|\|)\s*", "", v).strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
            v = v[1:-1]
        out[k] = v
    return out


def main():
    cfg = json.loads((ROOT / "groups.json").read_text(encoding="utf-8"))
    groups = cfg["groups"]
    on_disk = {p.parent.name: p for p in SKILLS.glob("*/SKILL.md")}
    seen, errors = {}, []
    for pn in cfg["profiles"]:
        if pn in groups:
            errors.append(f"profile {pn} has the same name as a group")
    for g, spec in groups.items():
        for s in spec["skills"]:
            if s in seen:
                errors.append(f"{s}: in groups {seen[s]} and {g}")
            seen[s] = g
            if s not in on_disk:
                errors.append(f"{s}: listed in {g} but skills/{s}/SKILL.md missing")
    for s in on_disk:
        if s not in seen:
            errors.append(f"{s}: not in any group")
    meta = {}
    for s, p in on_disk.items():
        fm = frontmatter(p)
        meta[s] = fm
        if fm.get("name") != s:
            errors.append(f"{s}: frontmatter name is {fm.get('name')!r}")
        if not fm.get("description"):
            errors.append(f"{s}: empty description")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    out = ["# Skill index", "",
           "Generated by `scripts/build-index.py` from `groups.json` and each SKILL.md. Do not edit by hand.", "",
           f"{len(on_disk)} skills in {len(groups)} groups.", ""]
    for g, spec in groups.items():
        out += [f"## {g}: {spec['title']}", "", f"Use when: {spec['when']}", ""]
        for s in spec["skills"]:
            d = meta[s]["description"].replace("|", "/")
            if len(d) > 220:
                d = d[:217].rstrip() + "..."
            out.append(f"- `{s}`: {d}")
        out.append("")
    out += ["## Profiles", ""]
    for name, parts in cfg["profiles"].items():
        out.append(f"- `{name}`: {', '.join(parts)}")
    out.append("")
    (ROOT / "INDEX.md").write_text("\n".join(out), encoding="utf-8")
    print(f"OK: {len(on_disk)} skills, INDEX.md written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
